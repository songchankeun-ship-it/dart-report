"""최대주주변경·자기주식·감사의견 파서 검증."""
import json
from dart_client import extract_text
from parsers import parse_major_shareholder_change, parse_treasury_stock, parse_audit_report, structured_lines

def T(rows):
    html = "<TABLE>" + "".join("<TR>" + "".join(f"<TD>{c}</TD>" for c in r) + "</TR>" for r in rows) + "</TABLE>"
    return extract_text(html.encode("utf-8"))

ms = T([
    ["1. 변경내용", "변경전", "최대주주명", "김철수"],
    ["", "", "소유주식수(주)", "4,500,000"],
    ["", "", "소유비율(%)", "18.75"],
    ["", "변경후", "최대주주명", "주식회사 라마홀딩스"],
    ["", "", "소유주식수(주)", "6,000,000"],
    ["", "", "소유비율(%)", "25.00"],
    ["2. 변경사유", "주식양수도계약 이행에 따른 최대주주 변경"],
    ["3. 지분인수경위", "-"],
    ["4. 변경일자", "2026-10-20"],
    ["5. 변경확인일자", "2026-10-20"],
    ["6. 기타 투자판단과 관련한 중요사항", "- 양수도 금액: 30,000,000,000원"],
    ["- 경영권 변동 여부", "예"],
])
d = parse_major_shareholder_change(ms); print(json.dumps(d, ensure_ascii=False))
assert d["변경전_최대주주"] == "김철수" and d["변경후_최대주주"] == "주식회사 라마홀딩스"
assert d["변경전_지분율"] == 18.75 and d["변경후_지분율"] == 25.0 and d["지분율_변화"] == 6.25
assert d["변경후_주식수"] == 6_000_000 and d["변경일자"] == "2026-10-20" and d["경영권_변동"] == "예"
print("최대주주변경 OK\n", "\n".join(structured_lines(d)), "\n")

